/**
 * Builds docs/adr/README.md from the ADR files. Each ADR is `NNNN-short-title.md` and starts
 * with `# NNNN. Title`, a `**Status:**` line, and a one-line `**Summary:**`. `--check` fails on
 * a stale index, an ADR without those lines, or two ADRs with the same number.
 *
 * Plain JavaScript without dependencies: CI runs it on documentation-only changes too, before
 * anything is installed. The README's text lives here; edit it here, then run `pnpm adr`.
 */
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const DIR = fileURLToPath(new URL('../docs/adr/', import.meta.url));
const INDEX = join(DIR, 'README.md');

const HEADER = `# Architecture decision records

<!-- Generated by \`pnpm adr\` from the ADR files and scripts/adr-index.mjs. Do not edit by hand. -->

Short records of decisions made while building, with the reason and what would make us revisit them. The PRD and the Phase 0 plan stay the source of requirements; these record how they were met.

## Adding an ADR

- Write \`NNNN-short-title.md\`. Start it with \`# NNNN. Title\`, a \`**Status:**\` line, and a one-line \`**Summary:**\` of the decision, like the ADRs below.
- Number an ADR when its PR merges, not in a plan or brief. Use the next free number on \`main\`; if another PR takes that number first, renumber on rebase (file name, title, and references to it).
- Run \`pnpm adr\` to rebuild this index. \`pnpm adr:check\` (in \`pnpm verify\` and CI) fails on a stale index or on two ADRs with the same number.
- This file merges with git's union driver (\`.gitattributes\`), so a rebase keeps rows from both sides; run \`pnpm adr\` afterwards.
- When a later change refines a decision, amend its ADR in place with a dated "Update" section.
`;

const problems = [];
const adrs = [];
for (const file of (await readdir(DIR)).sort()) {
  if (file === 'README.md' || !file.endsWith('.md')) continue;
  const name = /^(\d{4})-[a-z0-9-]+\.md$/.exec(file);
  if (!name) {
    problems.push(`${file}: name it NNNN-short-title.md`);
    continue;
  }
  const text = await readFile(join(DIR, file), 'utf8');
  const title = /^# (\d{4})\. (.+)$/.exec(text.split('\n', 1)[0]);
  const status = /^\*\*Status:\*\* (.+)$/m.exec(text);
  const summary = /^\*\*Summary:\*\* (.+)$/m.exec(text);
  if (!title) problems.push(`${file}: the first line must be "# ${name[1]}. Title"`);
  else if (title[1] !== name[1]) problems.push(`${file}: the title says ${title[1]}`);
  if (!status) problems.push(`${file}: needs a "**Status:** ..." line`);
  if (!summary) problems.push(`${file}: needs a one-line "**Summary:** ..." line`);
  adrs.push({
    number: name[1],
    file,
    title: title?.[2].trim() ?? '',
    // "Accepted, 14 November 2026. Implements ..." -> "Accepted"
    status: status?.[1].split(/[,.]/, 1)[0].trim() ?? '',
    summary: summary?.[1].trim() ?? '',
  });
}

const files = new Map();
for (const adr of adrs) files.set(adr.number, [...(files.get(adr.number) ?? []), adr.file]);
for (const [number, names] of files) {
  if (names.length > 1) {
    problems.push(`${names.length} ADRs numbered ${number}: ${names.join(', ')}. Renumber one.`);
  }
}

const cell = (text) => text.replaceAll('|', '\\|');
const rows = adrs.map(
  (adr) =>
    `| [${adr.number}](${adr.file}) | ${cell(adr.title)} | ${cell(adr.summary)} | ${cell(adr.status)} |`,
);
const index = `${HEADER}
| ADR | Title | Decision | Status |
| --- | --- | --- | --- |
${rows.join('\n')}
`;

const current = await readFile(INDEX, 'utf8').catch(() => '');
if (process.argv.includes('--check')) {
  if (current !== index) problems.push('docs/adr/README.md is out of date: run `pnpm adr`');
} else if (current !== index) {
  await writeFile(INDEX, index);
}
if (problems.length > 0) {
  console.error(`ADR check failed:\n- ${problems.join('\n- ')}`);
  process.exit(1);
}
console.log(`ADR index is up to date (${adrs.length} ADRs).`);
