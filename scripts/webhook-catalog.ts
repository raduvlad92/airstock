/**
 * Writes the event catalog in docs/webhooks.md from the webhook event-type registry
 * (packages/core/src/webhooks/events.ts), between the `event-catalog` markers. A test fails when
 * the committed catalog is stale; run `pnpm webhooks:docs` after changing an event type.
 */
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { sampleEnvelope, WEBHOOK_EVENT_TYPES, type WebhookEventType } from '@airstock/core';

export const DOC_PATH = fileURLToPath(new URL('../docs/webhooks.md', import.meta.url));
const START = '<!-- event-catalog:start (generated by `pnpm webhooks:docs`; do not edit) -->';
const END = '<!-- event-catalog:end -->';

const FILTER_NAMES = { locations: 'warehouses and locations', alertKinds: 'alert kinds' };

function section(type: WebhookEventType): string {
  const filters = type.filters.length
    ? type.filters.map((f) => FILTER_NAMES[f]).join(', ')
    : 'none (always sent)';
  return [
    `### \`${type.id}\``,
    '',
    type.description,
    '',
    `- **Needs:** \`${type.permission}\` (held by whoever subscribes)`,
    `- **Filters:** ${filters}`,
    '',
    '```json',
    JSON.stringify(sampleEnvelope(type), null, 2),
    '```',
  ].join('\n');
}

export function renderCatalog(): string {
  const available = WEBHOOK_EVENT_TYPES.filter((t) => t.status === 'available');
  const coming = WEBHOOK_EVENT_TYPES.filter((t) => t.status === 'coming');
  return [
    START,
    '',
    ...available.map(section).flatMap((s) => [s, '']),
    '### Coming with later milestones',
    '',
    'Registered, listed by the API with `"status": "coming"`, hidden in the dashboard, and refused when subscribing until the milestone that emits them ships. The samples show the planned shape.',
    '',
    '| Type | Description | Filters |',
    '| --- | --- | --- |',
    ...coming.map(
      (t) =>
        `| \`${t.id}\` | ${t.description} | ${t.filters.map((f) => FILTER_NAMES[f]).join(', ') || 'none'} |`,
    ),
    '',
    END,
  ].join('\n');
}

export function withCatalog(doc: string): string {
  const start = doc.indexOf(START);
  const end = doc.indexOf(END);
  if (start < 0 || end < start) throw new Error('docs/webhooks.md has no event-catalog markers.');
  return `${doc.slice(0, start)}${renderCatalog()}${doc.slice(end + END.length)}`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const doc = await readFile(DOC_PATH, 'utf8');
  const next = withCatalog(doc);
  if (process.argv.includes('--check')) {
    if (next !== doc) {
      console.error('docs/webhooks.md is stale: run pnpm webhooks:docs');
      process.exit(1);
    }
  } else {
    await writeFile(DOC_PATH, next);
    console.log('Wrote the event catalog to docs/webhooks.md');
  }
}
